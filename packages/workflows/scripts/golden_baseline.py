"""
golden_baseline.py — snapshot the ladder's verdict for every recorded run.

The baseline is a characterisation test: it does not claim the current verdicts
are RIGHT, it claims they are KNOWN. Any gate or threshold change that silently
flips a verdict on a run nobody was looking at then fails tests/ with the run
named, instead of being discovered three weeks later on a customer's screen.

    python3 scripts/golden_baseline.py            # show what would change
    python3 scripts/golden_baseline.py --write    # commit the new baseline
"""

import argparse
import glob
import json
import os
import sys

_CREWS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _CREWS)

from zyg_workflows import qc_contract as qc  # noqa: E402

BASELINE = os.path.join(_CREWS, 'tests', 'golden', 'baseline.json')
PATTERNS = ('output/*/*/debug/report.json', 'output/*/debug/report.json')


def collect():
    runs = {}
    seen = set()
    for pat in PATTERNS:
        for path in sorted(glob.glob(os.path.join(_CREWS, pat))):
            if path in seen:
                continue
            seen.add(path)
            rel = os.path.relpath(path, _CREWS)
            run = os.path.basename(os.path.dirname(os.path.dirname(path)))
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    doc = json.load(f)
                checks = [c for q in doc.get('qc', []) for c in q.get('checks', [])]
                ev = qc.evaluate(checks)
            except Exception as e:
                print(f'  skip {run}: {e}')
                continue
            runs[run] = {
                'report': rel,
                'blocked': ev['blocked'],
                'passed_checks': ev['passed_checks'],
                'failed_checks': ev['failed_checks'],
                'unknown_checks': ev['unknown_checks'],
                'blocking_failures': sorted(set(ev['blocking_failures'])),
                'warning_failures': sorted(set(ev['warning_failures'])),
                'coverage_score': ev['coverage_score'],
                'uncovered_classes': ev['uncovered_classes'],
            }
    return runs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    args = ap.parse_args()

    runs = collect()
    blocked = sorted(r for r, v in runs.items() if v['blocked'])
    print(f'{len(runs)} recorded runs; {len(blocked)} would be BLOCKED by the current ladder:')
    for r in blocked:
        print(f'   {r:22s} {runs[r]["blocking_failures"]}')

    old = {}
    if os.path.exists(BASELINE):
        try:
            old = json.load(open(BASELINE, encoding='utf-8')).get('runs', {})
        except Exception:
            old = {}
    if old:
        drift = [
            r for r in sorted(set(old) | set(runs)) if old.get(r, {}).get('blocked') != runs.get(r, {}).get('blocked')
        ]
        print(f'\nverdict drift vs stored baseline: {", ".join(drift) if drift else "none"}')

    if not args.write:
        print('\n(dry run — pass --write to store)')
        return

    os.makedirs(os.path.dirname(BASELINE), exist_ok=True)
    payload = {
        '_README': [
            'AUTO-GENERATED by scripts/golden_baseline.py — do not hand-edit.',
            'A characterisation snapshot: these verdicts are KNOWN, not endorsed.',
            'Hand-labelled ground truth lives in labels.json instead.',
            'Regenerate deliberately, and say why in the commit message.',
        ],
        'gate_config': qc.load_config(force=True),
        'runs': runs,
    }
    tmp = BASELINE + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(payload, f, indent=1, ensure_ascii=False)
        f.write('\n')
    os.replace(tmp, BASELINE)
    print(f'\nwrote {BASELINE} ({len(runs)} runs)')


if __name__ == '__main__':
    main()

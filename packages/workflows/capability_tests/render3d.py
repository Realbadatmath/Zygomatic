def _p(pid, title, feeds, checks, scene, rows=ALL, **kw):
    p = {
        'id': pid,
        'title': title,
        'feeds': list(feeds),
        'inputs': {'fixture': BLEND + '#' + scene, 'key': MANIFEST + '#' + scene, 'prompt': None},
        'conditions': dict(COND),
        'checks': list(checks),
        'grade': 'measured',
        'rows': rows,
    }
    p.update(kw)
    return p


def _op(question):
    return {'check': 'operator', 'blind': True, 'question': question, 'when': 'render'}



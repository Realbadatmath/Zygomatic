"""Default test — Get a finished picture out of the geometry (render3d). 2026-09-30.

Question the sheet asks: can we get a FINISHED picture out of the geometry?
"Finished" is the house standard, not "rendered": the finished-drawing portfolio rule
([[feedback_finished_build_ten_shots]]) says a look is only proven by forty-plus pictures and a
measured audit, and every blind judgement below is made at the operator's working zoom of 67 %,
because that is the size the picture is actually accepted at.

The three rows are not models, they are RENDERERS, and none of them takes a prompt:

  cycles          the photoreal path — char_cycles_render.py, path-traced, Principled BSDF /
                  Principled Hair BSDF, GPU ([[project_charstudio_cycles_render]]). Its own
                  bench records 900x1125 at 128 samples = ~7 s render, ~22 s wall with the build.
  eevee           the viewport/realtime path ([[project_charstudio_viewport_realism]]): a
                  rasteriser. Fast, and it does NOT path-trace, which is why the noise-versus-
                  samples question is `na` on it rather than answered badly.
  sheet_renderer  blender_scripts/render_asset_previews.py — the generic GLB-to-sheet renderer:
                  ORTHOGRAPHIC camera on a fixed 3/4 vector whose scale is solved from the
                  model's own bbox, EEVEE Next at 96 TAA samples when a GL context exists and
                  Cycles CPU at 64 samples with denoising when it does not, 256 px per item
                  ([[project_generic_sheet_renderer]]). It has no aperture, so depth of field is
                  `na` on that row, and its engine is chosen at run time, so the noise curve is
                  `na` too.

Shape of the test
-----------------
One fixture .blend holding every scene this test needs (the CC0 Blender Studio base body, a
six-ball material set, a scripted three-point rig over a shadow-catcher floor, a glass sphere on
a checkerboard backdrop, a depth-of-field ruler, a 12-cell sheet and an eight-camera orbit), plus
a MANIFEST.json holding the ANSWER KEYS — the six material names in their true order, the key
light's azimuth and elevation, the asked cell exposure. Nothing here is generated by this task:
the .blend is declared with the exact command that builds it and the MANIFEST is declared
UNVERIFIED, which BLOCKS materials_render, lighting_render and consistency until the operator
has looked at the six balls and the rig and signed the key off.

What machines decide and what the operator decides
--------------------------------------------------
Every geometric and photometric property of a render is measurable and is measured: shadow
direction from the rendered shadow against the key light's azimuth, focus separation from the
Laplacian variance ratio between the focus plane and the backdrop, path-tracing noise from the
standard deviation of a flat patch, sheet consistency from per-cell mean luma, passes from the
files and their variance, alpha from the PNG's own alpha channel, headlessness from the exit code
and stderr. What no machine on this box decides is whether the picture READS AS FINISHED — the
defect-judge bench of 2026-09-27 put the best local VLM at 34/40 on a global "is this right"
question and 2/8 on the hard cases — so realism, materials, shadows, glass and the turntable
carry a written, blind operator question on top of (never instead of) whatever ran mechanically.

Prompt bands
------------
All three rows are headless Blender scripts driven by parameters, not by wording. The four
prompt bands are therefore `na` for the whole step with the reason on every cell; the settings
that DID produce a picture are still measured, under `receipts` in Operability.
"""


"""Default test — Body fit (body_fit). 2026-09-30.

Question the sheet asks: "Can we recover a 3D body from a rendered clip, and what does it
cost?" The sheet's own limitation says the rest out loud — *speed and plumbing are measured;
ACCURACY of the fit is not. Nobody has compared a fitted body against a known ground truth
here.* That sentence is the whole reason this module exists, so everything below is built
around one idea: a fit is only measurable against something we already know the answer to.

The shape of the test
---------------------
Two ground truths, not one, because the two rows can answer different questions:

  A. VERIFIED 2D KEYPOINTS. Twenty frames pulled from the Movement Studio captures, with a
     human-marked keypoint set. Every row can be scored against these by projecting its
     result back into the image with the run's own camera (`keypoint_error_px`). The marks
     do not exist yet: the manifest ships with an empty `verified_joints` list and every
     column it feeds is BLOCKED until the operator fills it. We do not grade a fit against
     an answer nobody checked.

  B. A SYNTHETIC POSED TRUTH. Twelve frames rendered from a Blender scene we posed
     ourselves, so every joint's world position AND its global rotation are known exactly,
     to the millimetre and the degree — the only way `rotation` and `shape` can be honest
     questions at all. The fixture is generated by a bpy script named in `fixtures`; it is
     `verified: True` because the truth is the scene file, not somebody's opinion of it.

What a row can and cannot be asked
----------------------------------
`sam3d_body` returns a 3D body (vertices, 127 joint coordinates, 127 joint global
rotations). `mediapipe_2d` returns image-plane landmarks with a relative depth that is not
metric. So each check carries `when`:

    when='proj2d'   scored in the image plane — every row can answer it
    when='fit3d'    needs metric 3D joints/vertices — a 2D row SKIPS it (recorded skipped,
                    never counted as a pass)

and `mediapipe_2d` is `na` outright on `rotation`, `shape` and `scale_fit`, which have no
image-plane meaning at all.

Honest judging
--------------
Every mechanical number here is a real measurement (reprojection error in pixels, 3D error
in millimetres, geodesic rotation error in degrees, stature in metres) — no VLM is asked
whether a fit "looks right", because the 2026-09-27 defect bench says no local model can
tell. Where a number cannot settle it — is the fitted body following THIS person, is the
silhouette actually on the subject under a cloak — a BLIND operator yes/no on a fixed
overlay render runs beside the number, and the mechanical check is a VETO: it can only make
a trial fail, never rescue one.

A fitter has no prompt. The four Prompt bands are `na` at step level with the reason.

Blocked on purpose: `accuracy` and everything else that leans on fixture A stays `untested
— key unverified` until the twenty frames are marked by hand. That is the honest state.
"""


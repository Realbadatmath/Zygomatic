CHECK_KINDS = {
    'chroma_corr_min': "mean cosine of the render's 12-bin CQT chroma (1 frame per beat, energy-normalised) against the chroma of the plan's MIDI, best score over lags in +/- `lag_bars` bars; passes when >= `min` AND >= `null` + `margin`, where `null` is the mean score of the same render against the other cues of the run",
    'key_equals': 'Krumhansl-Schmuckler profile correlation on the whole-file chroma names the key; passes when it equals `key` and `mode`, enharmonic spellings accepted',
    'tempo_bpm_range': 'librosa.beat.tempo (aggregate median, hop 512) within +/- `tolerance` BPM of `bpm`',
    'chord_template_share': "per bar, the chroma of that bar is correlated against the 24 major/minor triad templates; passes when the bar's asked chord from `chords` ranks first for >= `share` of the bars",
    'section_bounds_within': 'change points of the onset-strength energy envelope (ruptures, Pelt, rbf) fall within +/- `bars` bars of the boundaries in `at_bars`, for >= `share` of them',
    'ending_drop_db': 'RMS of the last `tail_s` s is >= `min_db` below the RMS of the preceding `body_s` s AND the tail is not a fade: the dB envelope over the tail has a single change point rather than a constant negative slope (fade => fail)',
    'loop_seam_residual_max': 'butt the file end to the file start over a `ms` ms window; RMS of the difference between that seam and the same window inside the body is <= `max_db` dB',
    'voice_cosine_min': 'TitaNet-large speaker embedding of the demucs-separated vocal stem; cosine >= `min` for every pair of the repeats (a new singer per take fails)',
    'stem_file_count': 'the call made with stems requested returns >= `min` separate audio files, each decodable and within 0.1 s of the mix duration',
}


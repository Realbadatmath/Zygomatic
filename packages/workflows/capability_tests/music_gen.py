"""Default test — Music generation (music_gen). 2026-09-30.

Question the sheet asks: can a generative music model be held to a WRITTEN PLAN — the notes,
not just the key? The sheet already carries the measured answer for one row (verdict, 2026-09-27:
no — ACE-Step's chroma similarity to the composed plan was 0.279 against a 0.252 cross-song null,
z = +0.65, while the deterministic score render scored 0.827, z = +2.84 on the same test). This
module turns that one measurement into the fixed test every music row is put through.

Shape of the test: ONE composed cue — "The Harbour Lantern", a 60 s children's song in D major
at 96 BPM, 4/4, 32 bars, with a named section plan, a fixed four-bar chord loop, three named
instruments and a four-line lyric — is handed to every row in the form that row accepts. The
score renderer gets the plan's note data. ACE-Step gets the caption the house builds from the
SAME plan (tags, key, tempo, metre, lyric — no note data ever reaches it, which is exactly what
`melody` measures). Every row is then scored against the plan, mechanically wherever a detector
exists (chroma, key, tempo, chord templates, energy change points, Whisper WER, CLAP ranking,
LUFS/true-peak through audio_qc) and by a BLIND operator where no detector can be trusted
(intelligibility, the hook, the kids screen).

What is blocked and why: the plan itself is a FIXTURE (the same notes must reach every row) and
it is not on disk yet. `fixtures` carries the exact command that makes it; until the operator has
opened it and checked that it is the cue described here, `melody`, `chords` and `structure` are
written `untested — key unverified`. Nothing is generated by this module.

`plagiarism` is `na`: there is no local fingerprint corpus to match a 30 s excerpt against, and a
vendor claim about training data is not a measurement of this render.
"""


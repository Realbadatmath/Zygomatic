def _p(pid, title, feeds, checks, cond=None, inputs=None, **kw):
    p = {
        'id': pid,
        'title': title,
        'feeds': list(feeds),
        'inputs': dict(inputs or {'prompt': CAPTION, 'fixture': PLAN_JSON}),
        'conditions': dict(cond or COND),
        'checks': list(checks),
        'grade': 'measured',
        'rows': list(ALL),
    }
    p.update(kw)
    return p



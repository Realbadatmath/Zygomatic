def collect(out_dir, items):
    os.makedirs(out_dir, exist_ok=True)
    manifest = []
    for n, (src, caption) in enumerate(items):
        if not src or not os.path.exists(src):
            continue
        name = '%02d_%s' % (n, os.path.basename(src))
        shutil.copyfile(src, os.path.join(out_dir, name))
        manifest.append({'file': name, 'caption': caption})
    with open(os.path.join(out_dir, 'files.json'), 'w') as f:
        json.dump(manifest, f, indent=1)
    with open(os.path.join(out_dir, 'gallery.html'), 'w') as f:
        f.write(PAGE)
    return manifest



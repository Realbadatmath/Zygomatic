"""review_gallery.py — publish everything built for the forest scene for eyeball review.

RUN:
    python3 -m zyg_workflows.geom.review_gallery [-o output/axe_forest/REVIEW] [--port 8909]

Collects the hero plates, the four ControlNet conditioning maps, the licence-checked
reference sheets and the gate report into one page with left/right arrow navigation.

Two hard-won details are baked in rather than rediscovered:
  * the page is gallery.html and never index.html — an index.html suppresses the static
    server's directory listing, and the listing was how the manifest got built;
  * files.json is written alongside, because the page cannot enumerate a directory.
"""


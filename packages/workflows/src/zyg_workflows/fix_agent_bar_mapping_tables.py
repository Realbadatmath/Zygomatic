def tier_mapping() -> Dict[str, int]:
    """Return a fresh copy of the tier-name to tier-number table.

    In: nothing. Out: a new ``dict`` mapping each tier name ('Specialist' …
    'Executive') to its integer rank 1-5.
    """
    return dict(_TIER_MAPPING)


def gpu_model_names() -> Set[str]:
    """Return a fresh copy of the set of model names that belong on the GPU schedule.

    In: nothing. Out: a new ``set`` of display names as they appear in
    ``gpu_ai_models.json``.
    """
    return set(_GPU_MODELS)


def agent_ai_model_mapping() -> Dict[str, List[str]]:
    """Return a fresh copy of the model-name to agent-names table.

    In: nothing. Out: a new ``dict`` whose keys are AI model display names and
    whose values are new ``list`` objects of the agent names that use them, so
    mutating one caller's lists cannot affect another's.
    """
    return {model: list(agents) for model, agents in _AGENT_AI_MODEL_MAPPING.items()}


def resolve_dirs(agents_dir: str, schedule_dir: str) -> Tuple[Path, Path, Path]:
    """Turn the two constructor arguments into the three paths the fixer uses.

    In: ``agents_dir`` (resolved against the current working directory) and
    ``schedule_dir`` (kept relative if it is relative). Out: the tuple
    ``(agents_dir, schedule_dir, index_path)`` where ``index_path`` is
    ``agents_dir / 'index.json'``.
    """
    agents = Path(os.path.abspath(agents_dir))
    schedule = Path(schedule_dir)
    return agents, schedule, agents / 'index.json'

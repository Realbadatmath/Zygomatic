# ── normalising ──────────────────────────────────────────────────────────────
def _norm(w) -> str:
    s = unicodedata.normalize('NFKD', str(w or ''))
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.lower().strip().strip('"\'`?!.,;:()[]')
    return re.sub(r'\s+', ' ', s)



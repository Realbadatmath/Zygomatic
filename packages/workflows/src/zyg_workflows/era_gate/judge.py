# ── tiling ───────────────────────────────────────────────────────────────────


def tile_boxes(
    width: int, height: int, cols: int = 3, rows: int = 2, overlap: float = 0.12
) -> list[tuple[int, int, int, int]]:
    """Pixel boxes (x0,y0,x1,y1) of a cols x rows grid with fractional overlap."""
    boxes = []
    tw = width / cols
    th = height / rows
    ox = tw * overlap
    oy = th * overlap
    for r in range(rows):
        for c in range(cols):
            x0 = max(0, int(round(c * tw - ox)))
            y0 = max(0, int(round(r * th - oy)))
            x1 = min(width, int(round((c + 1) * tw + ox)))
            y1 = min(height, int(round((r + 1) * th + oy)))
            boxes.append((x0, y0, x1, y1))
    return boxes


def make_tiles(
    image_path: str, out_dir: str, cols: int = 3, rows: int = 2, min_long: int = 896
) -> tuple[list[str], list[tuple[int, int, int, int]], tuple[int, int]]:
    """Write the full frame + enlarged tiles to out_dir. Returns (paths, boxes, (W,H)).

    paths[0] is the full frame; paths[1:] are the tiles in reading order. Tiles
    are Lanczos-upscaled so their long side is at least `min_long` px — this
    adds no information, but it is what makes a small object occupy enough of
    the judge's token grid to be seen (the crop rule).
    """
    from PIL import Image

    with Image.open(image_path) as im:
        im = im.convert('RGB')
        W, H = im.size
        boxes = tile_boxes(W, H, cols, rows)
        full_p = os.path.join(out_dir, 'frame_full.jpg')
        full = im.copy()
        if max(full.size) > 1600:
            full.thumbnail((1600, 1600), Image.LANCZOS)
        full.save(full_p, 'JPEG', quality=92)
        paths = [full_p]
        for k, (x0, y0, x1, y1) in enumerate(boxes):
            t = im.crop((x0, y0, x1, y1))
            long = max(t.size)
            if long < min_long:
                s = min_long / float(long)
                t = t.resize((max(1, int(t.width * s)), max(1, int(t.height * s))), Image.LANCZOS)
            p = os.path.join(out_dir, f'tile_{k}.jpg')
            t.save(p, 'JPEG', quality=92)
            paths.append(p)
    return paths, boxes, (W, H)


def map_tile_bbox(bbox_unit: list | None, tile_idx: int, boxes: list, size: tuple) -> list | None:
    """Unit bbox on tile `tile_idx` (1-based in the image list) -> frame 0-1000 bbox."""
    if not bbox_unit or tile_idx is None:
        return None
    W, H = size
    try:
        bx0, by0, bx1, by1 = [float(v) for v in bbox_unit]
    except Exception:
        return None
    if tile_idx == 0:
        x0, y0, x1, y1 = 0, 0, W, H
    else:
        k = tile_idx - 1
        if k < 0 or k >= len(boxes):
            return None
        x0, y0, x1, y1 = boxes[k]
    fx0 = x0 + bx0 * (x1 - x0)
    fy0 = y0 + by0 * (y1 - y0)
    fx1 = x0 + bx1 * (x1 - x0)
    fy1 = y0 + by1 * (y1 - y0)
    return [
        int(round(1000 * fx0 / W)),
        int(round(1000 * fy0 / H)),
        int(round(1000 * fx1 / W)),
        int(round(1000 * fy1 / H)),
    ]


def bbox_area_frac(bbox_1000: list | None) -> float:
    if not bbox_1000 or len(bbox_1000) != 4:
        return 1.0
    x0, y0, x1, y1 = bbox_1000
    return max(0.0, (x1 - x0) / 1000.0) * max(0.0, (y1 - y0) / 1000.0)


def _preamble(era: dict | None, n_tiles: int) -> str:
    lbl = (era or {}).get('period_label') or 'a historical period'
    return (
        f'These images are enlarged overlapping crops of ONE still frame from a historical '
        f'documentary set in {lbl}, generated by a diffusion model — they are NOT a video '
        f'sequence. Judge what is ACTUALLY VISIBLE in the crops, not what the scene is '
        f'supposed to contain. Answer strictly yes or no.'
    )


def _preamble_frame(era: dict | None) -> str:
    lbl = (era or {}).get('period_label') or 'a historical period'
    return (
        f'This is a still frame from a historical documentary set in {lbl}, generated by a '
        f'diffusion model. Answer about what is ACTUALLY VISIBLE. Answer strictly yes or no.'
    )


# ── judging ──────────────────────────────────────────────────────────────────


def judge_frame(
    image_path: str,
    items: list[dict],
    era: dict | None,
    *,
    tier: str = 'resident',
    api_key: str = '',
    api_model: str = 'claude-haiku-4-5-20251001',
    prefer: str = 'local',
    log: Callable | None = None,
    keep_tiles: bool = False,
    record_usage: Callable | None = None,
    local_ok: bool = True,
) -> dict:
    """Judge one frame. Returns
    {'skipped': bool, 'judge': 'qwen3vl'|'haiku'|'', 'flags': [...], 'unknown': [...],
     'answers': {id: 'yes'|'no'|'unknown'}, 'seconds': float, 'reason': str}

    A flag = {'id', 'question', 'reason', 'bbox' (frame 0-1000 or None), 'fix',
              'severity', 'small', 'tile'}.  ok := no critical flags.
    """

    def _l(m):
        if log:
            try:
                log(m)
            except Exception as _exc:
                _zyg_log.debug('log callback failed: %s', _exc)

    t0 = time.time()
    res = {'skipped': True, 'judge': '', 'flags': [], 'unknown': [], 'answers': {}, 'seconds': 0.0, 'reason': ''}
    if not items:
        res.update({'skipped': False, 'reason': 'no items'})
        return res
    if not os.path.isfile(image_path):
        res['reason'] = 'frame missing'
        return res
    tmp = tempfile.mkdtemp(prefix='eragate_')
    try:
        try:
            paths, boxes, size = make_tiles(image_path, tmp)
        except Exception as e:
            res['reason'] = f'tiling failed: {e!r}'
            return res
        n_tiles = len(paths) - 1
        tile_idx = list(range(1, len(paths)))
        payload = []
        for it in items:
            scope = it.get('scope', 'tiles')
            rec = dict(it)
            rec['frame_indices'] = [0] if scope == 'frame' else tile_idx
            payload.append(rec)

        out = None
        order = ['local', 'api'] if prefer == 'local' else ['api', 'local']
        if not local_ok or os.environ.get('ZYG_ERA_GATE_NO_LOCAL', '0') == '1':
            order = [w for w in order if w != 'local']
        for which in order:
            if which == 'local':
                out = _judge_local(paths, payload, era, tier, n_tiles, _l)
            else:
                out = _judge_api(paths, payload, era, api_key, api_model, _l, record_usage)
            if out is not None:
                break
        if out is None:
            res['reason'] = 'no judge available (local judge declined, no API key or API failed)'
            res['seconds'] = round(time.time() - t0, 1)
            return res
        judge, verdicts = out
        res['judge'] = judge
        res['skipped'] = False
        for it in items:
            v = verdicts.get(it['id']) or {}
            ans = str(v.get('answer') or 'unknown')
            res['answers'][it['id']] = ans
            if ans == 'unknown':
                res['unknown'].append(it['id'])
                continue
            if ans != it.get('expected', 'no'):
                bb = None
                if v.get('bbox') is not None:
                    bb = map_tile_bbox(v.get('bbox'), v.get('bbox_frame'), boxes, size)
                res['flags'].append(
                    {
                        'id': it['id'],
                        'question': it['question'],
                        'reason': str(v.get('reason') or '')[:160],
                        'bbox': bb,
                        'fix': it.get('fix', ''),
                        'severity': it.get('severity', 'critical'),
                        'small': bool(it.get('small')) and bb is not None and bbox_area_frac(bb) < 0.06,
                        'tile': v.get('bbox_frame'),
                        'source': it.get('source', ''),
                    }
                )
        res['seconds'] = round(time.time() - t0, 1)
        return res
    finally:
        if not keep_tiles:
            try:
                import shutil

                shutil.rmtree(tmp, ignore_errors=True)
            except Exception as _exc:
                _zyg_log.debug('tile temp dir cleanup skipped: %s', _exc)


def _judge_local(paths, payload, era, tier, n_tiles, _l):
    """Qwen3-VL through vlm_inspector. None when it cannot run (never a pass)."""
    try:
        from zyg_workflows import vlm_inspector as VI
    except Exception as e:
        _l(f'era_gate: vlm_inspector unavailable ({e!r})')
        return None
    try:
        if not VI.available():
            return None
        # Headroom guard, same as the typography judge: never the cpu tier
        # mid-render (126 s/frame stalled the Catherine run).
        try:
            need = float(VI.TIERS[tier]['min_free_gb'])
        except Exception:
            need = 14.0
        free = None
        try:
            from zyg_workflows.vram_manager import _get_free_vram_gb as _fv

            free = float(_fv())
        except Exception as _exc:
            _zyg_log.debug('free vram probe failed, skipping the headroom guard: %s', _exc)
        if free is not None and free < need:
            _l(f'era_gate: local judge needs {need:.0f} GB, {free:.1f} GB free — API judge')
            return None
        tile_items = [dict(p, frames='all') for p in payload if p['frame_indices'] != [0]]
        frame_items = [dict(p, frames='all') for p in payload if p['frame_indices'] == [0]]
        verdicts = {}
        for group, pre in ((tile_items, _preamble(era, n_tiles)), (frame_items, _preamble_frame(era))):
            if not group:
                continue
            r = VI.inspect_frames(
                paths, items=group, preamble=pre, tier=tier, offload=False, frame_kind='all', log_fn=_l
            )
            if not r or r.get('skipped'):
                return None
            if str(r.get('tier') or '') == 'cpu':
                _l('era_gate: judge downshifted to cpu — discarding, API judge')
                return None
            for v in r.get('verdicts') or []:
                verdicts[v['id']] = {
                    'answer': v.get('answer'),
                    'reason': v.get('reason'),
                    'bbox': v.get('bbox'),
                    'bbox_frame': v.get('bbox_frame'),
                }
        return 'qwen3vl', verdicts
    except Exception as e:
        _l(f'era_gate: local judge failed ({e!r})')
        return None


def _judge_api(paths, payload, era, api_key, api_model, _l, record_usage=None):
    """One Anthropic vision call with the full frame + tiles and every question."""
    if not api_key:
        return None
    try:
        import anthropic  # noqa: F401  availability probe: the client itself comes from subscription_llm below
    except Exception:
        return None
    try:
        content = []
        for i, p in enumerate(paths):
            with open(p, 'rb') as fh:
                raw = fh.read()
            b64 = base64.b64encode(raw).decode()
            # The full frame may be PNG bytes in a .jpg (ComfyUI output); the
            # API validates the bytes, so declare what is actually there.
            mt = (
                'image/png' if raw[:8] == b'\x89PNG\r\n\x1a\n' else 'image/webp' if raw[:4] == b'RIFF' else 'image/jpeg'
            )
            content.append(
                {
                    'type': 'text',
                    'text': f'IMAGE {i}' + (' (full frame)' if i == 0 else f' (crop {i} of {len(paths) - 1})'),
                }
            )
            content.append({'type': 'image', 'source': {'type': 'base64', 'media_type': mt, 'data': b64}})
        qlines = []
        for it in payload:
            which = 'IMAGE 0 only' if it['frame_indices'] == [0] else f'crops 1-{len(paths) - 1}'
            qlines.append(f'  "{it["id"]}": {it["question"]}  [look at {which}]')
        lbl = (era or {}).get('period_label') or 'a historical period'
        content.append(
            {
                'type': 'text',
                'text': (
                    f'IMAGE 0 is a still frame from a historical documentary set in {lbl}, generated by a '
                    f'diffusion model; images 1-{len(paths) - 1} are enlarged overlapping crops of that same '
                    f'frame (reading order: top-left, top-centre, top-right, bottom-left, bottom-centre, '
                    f'bottom-right). Answer each question strictly from what is ACTUALLY VISIBLE. For a '
                    f'yes on a crop question, give the crop number and a bounding box [x1,y1,x2,y2] in '
                    f'0-1000 coordinates of THAT crop around the offending object.\n\nQuestions:\n'
                    + '\n'.join(qlines)
                    + '\n\nReply with ONLY a JSON object: {"answers": {"<id>": {"answer": "yes"|"no", '
                    '"reason": "<short>", "image": <n or null>, "bbox": [x1,y1,x2,y2] or null}}}'
                ),
            }
        )
        from zyg_workflows.subscription_llm import anthropic_client as _sub_client

        r = _sub_client(api_key).messages.create(
            model=api_model, max_tokens=1500, temperature=0.0, messages=[{'role': 'user', 'content': content}]
        )
        if record_usage:
            try:
                record_usage(api_model, r.usage.input_tokens, r.usage.output_tokens)
            except Exception as _exc:
                _zyg_log.warning('token usage recording failed, this api judge call is unaccounted: %s', _exc)
        raw = re.sub(r'```(?:json)?|```', '', r.content[0].text).strip()
        m = re.search(r'\{.*\}', raw, re.S)
        d = json.loads(m.group(0) if m else raw)
        answers = d.get('answers') or {}
        verdicts = {}
        for it in payload:
            a = answers.get(it['id']) or {}
            ans = str(a.get('answer') or '').strip().lower()
            ans = 'yes' if ans.startswith('y') else 'no' if ans.startswith('n') else 'unknown'
            bb = a.get('bbox')
            bbu = None
            img = a.get('image')
            if isinstance(bb, (list, tuple)) and len(bb) == 4:
                try:
                    vals = [float(x) for x in bb]
                    bbu = [min(1.0, max(0.0, v / 1000.0)) for v in vals] if max(vals) > 1.0 else vals
                except Exception:
                    bbu = None
            try:
                img = int(img) if img is not None else None
            except Exception:
                img = None
            verdicts[it['id']] = {
                'answer': ans,
                'reason': str(a.get('reason') or '')[:160],
                'bbox': bbu,
                'bbox_frame': img,
            }
        return 'haiku', verdicts
    except Exception as e:
        _l(f'era_gate: API judge failed ({e!r})')
        return None


# ── region repair for small items ────────────────────────────────────────────


def region_repair(
    image_path: str,
    flag: dict,
    era: dict | None,
    *,
    seed: int = 0,
    log: Callable | None = None,
    judge_kwargs: dict | None = None,
) -> dict:
    """Repaint one small flagged region (a watch, a bulb, a sneaker) in place.

    Uses the existing Qwen InstantX inpaint graph (hand_fixer_qwen_inpaint) via
    ComfyUI: crop a square around the bbox, mask the bbox, repaint with the
    item's period 'fix' phrase, paste back through a feathered mask. Accepted
    only if the SAME question then answers 'no' on the repaired crop — a repair
    that cannot be verified is not a repair. Never touches pixels outside the
    mask (composited, not replaced).
    """

    def _l(m):
        if log:
            try:
                log(m)
            except Exception as _exc:
                _zyg_log.debug('log callback failed: %s', _exc)

    res = {'repaired': False, 'reason': '', 'bbox': flag.get('bbox')}
    bb = flag.get('bbox')
    if not bb or bbox_area_frac(bb) >= 0.06:
        res['reason'] = 'no small bbox'
        return res
    try:
        from zyg_workflows import _comfy_client as _comfy

        if not (_comfy.is_enabled() and _comfy.server_reachable()):
            res['reason'] = 'ComfyUI unavailable'
            return res
        wf = _comfy.load_workflow('hand_fixer_qwen_inpaint')
    except Exception as e:
        res['reason'] = f'inpaint graph unavailable ({e!r})'
        return res
    from PIL import Image, ImageDraw, ImageFilter

    try:
        base = Image.open(image_path).convert('RGB')
    except Exception as e:
        res['reason'] = f'cannot open ({e!r})'
        return res
    W, H = base.size
    x0, y0, x1, y1 = [int(v) for v in bb]
    px0, py0 = int(x0 * W / 1000), int(y0 * H / 1000)
    px1, py1 = int(x1 * W / 1000), int(y1 * H / 1000)
    bw, bh = max(8, px1 - px0), max(8, py1 - py0)
    side = int(min(max(max(bw, bh) * 3, 512), max(W, H)))
    cx, cy = (px0 + px1) // 2, (py0 + py1) // 2
    cx0 = max(0, min(W - side, cx - side // 2))
    cy0 = max(0, min(H - side, cy - side // 2))
    cx1, cy1 = min(W, cx0 + side), min(H, cy0 + side)
    crop = base.crop((cx0, cy0, cx1, cy1))
    mask = Image.new('L', crop.size, 0)
    d = ImageDraw.Draw(mask)
    pad_x, pad_y = int(bw * 0.2), int(bh * 0.2)
    d.rectangle((px0 - cx0 - pad_x, py0 - cy0 - pad_y, px1 - cx0 + pad_x, py1 - cy0 + pad_y), fill=255)
    tmpd = tempfile.mkdtemp(prefix='erarepair_')
    crop_p = os.path.join(tmpd, 'source.png')
    mask_p = os.path.join(tmpd, 'mask.png')
    work = crop.copy()
    if max(work.size) < 1024:
        s = 1024 / float(max(work.size))
        work = work.resize((int(work.width * s) // 16 * 16, int(work.height * s) // 16 * 16), Image.LANCZOS)
    mask_w = mask.resize(work.size, Image.NEAREST).convert('RGB')
    work.save(crop_p)
    mask_w.save(mask_p)
    fix = str(flag.get('fix') or '').strip()
    lbl = (era or {}).get('period_label') or 'the period'
    prompt = (
        (
            f'{fix}, {lbl}, seamless with the surrounding scene, same lighting and film grain, '
            f'photorealistic period reconstruction'
        )
        if fix
        else f'period-accurate {lbl} detail, seamless'
    )
    try:
        overrides = {
            '14': {'image': _comfy.stage_input_image(crop_p)},
            '46': {'image': _comfy.stage_input_image(mask_p)},
            '20': {'text': prompt},
            '21': {
                'text': 'wristwatch, bangle, painted nails, light bulb, electric light, sneaker, '
                'trainer, printed sign, logo, glass window, modern, blurry, text'
            },
            '31': {'seed': int(seed) + 4241, 'steps': 20, 'denoise': 1.0, 'cfg': 2.5},
        }
        outs = _comfy.submit(wf, overrides=overrides, timeout_s=600)
    except Exception as e:
        res['reason'] = f'inpaint failed ({e!r})'
        return res
    finally:
        for p in (crop_p, mask_p):
            try:
                os.remove(p)
            except OSError as _exc:
                _zyg_log.debug('inpaint temp file cleanup skipped: %s', _exc)
    if not outs:
        res['reason'] = 'inpaint produced no output'
        return res
    try:
        with Image.open(outs[0]) as o:
            fixed = o.convert('RGB').resize(crop.size, Image.LANCZOS)
    except Exception as e:
        res['reason'] = f'cannot read output ({e!r})'
        return res
    feather = mask.filter(ImageFilter.GaussianBlur(max(2, min(bw, bh) // 8)))
    cand_crop = crop.copy()
    cand_crop.paste(fixed, (0, 0), feather)
    # verify: the same question on the repaired crop must now answer 'no'
    vpath = os.path.join(tmpd, 'verify.jpg')
    v = cand_crop.copy()
    if max(v.size) < 896:
        s = 896 / float(max(v.size))
        v = v.resize((int(v.width * s), int(v.height * s)), Image.LANCZOS)
    v.save(vpath, 'JPEG', quality=92)
    item = {
        'id': flag['id'],
        'question': flag['question'],
        'expected': 'no',
        'severity': 'critical',
        'grounding': False,
        'scope': 'frame',
        'fix': fix,
        'small': False,
    }
    jr = judge_frame(vpath, [item], era, **(judge_kwargs or {}), log=log)
    ans = (jr.get('answers') or {}).get(flag['id'], 'unknown')
    if jr.get('skipped') or ans != 'no':
        res['reason'] = f'repair not verified (answer={ans}, judge={jr.get("judge") or "none"})'
        return res
    out = base.copy()
    out.paste(cand_crop, (cx0, cy0))
    out.save(image_path, 'JPEG', quality=95)
    res.update({'repaired': True, 'reason': 'verified clean', 'judge': jr.get('judge')})
    try:
        import shutil

        shutil.rmtree(tmpd, ignore_errors=True)
    except Exception as _exc:
        _zyg_log.debug('repaint temp dir cleanup skipped: %s', _exc)
    return res


def ladder_qualifier(flags: list[dict], era: dict | None, *, positive_only: bool = True) -> str:
    """The prompt clause the retry ladder appends for a set of flags.

    Positive phrasing only by default — FLUX.1-schnell discards negatives; Qwen
    (real CFG) gets the same clause plus its live negative list elsewhere.
    """
    parts, seen = [], set()
    for f in flags or []:
        fx = str(f.get('fix') or '').strip()
        if not fx or fx in seen:
            continue
        seen.add(fx)
        parts.append(fx)
    if not parts:
        return ''
    lbl = (era or {}).get('period_label') or 'the period'
    return ', ' + ', '.join(parts) + f', strictly period-accurate {lbl}'

def _tag_sentence(sentence: str, topic: str) -> str:
    """The keyword tag for *sentence*: the `_TAG_KEYWORDS` entry whose keyword
    list has the most hits in the lowercased sentence, ties going to the entry
    seen first. With no hit at all the tag is `'<topic> related imagery'`, the
    generic fallback the stage's quality gate counts."""
    _sl = sentence.lower()
    _best_tag = topic + ' related imagery'
    _best_count = 0
    for _tag, _kws in _TAG_KEYWORDS.items():
        _count = sum(1 for _kw in _kws if _kw in _sl)
        if _count > _best_count:
            _best_count = _count
            _best_tag = _tag
    return _best_tag

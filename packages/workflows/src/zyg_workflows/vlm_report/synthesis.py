"""STEP 5 — the out-of-process text-only synthesis that writes the report."""

import json
import os
import subprocess
import time

from zyg_workflows.vlm_report.constants import SYNTH_TOKENS, SYNTH_WAIT_S

# ── STEP 5: the LLM writes the report ────────────────────────────────────────

_SYNTH_RUNNER = '''"""Generated by vlm_report.py — runs ONE text-only synthesis in the judge venv.

It exists because vlm_worker.py's CLI is checklist-shaped: it truncates every
reply to 400 characters and caps generation at 256 tokens, both fatal to a
multi-paragraph report. Rather than reimplement model loading, this imports the
worker's own _load_model / _prepare_inputs / _generate, so the synthesis runs on
exactly the same code path (and the same quantization handling) as the judging.
A 224x224 neutral placeholder image is supplied because the Qwen3-VL processor
path always indexes images[0]; the prompt tells the model to ignore it.
"""
import json, os, sys

vlm_home, payload_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, vlm_home)


def _err(msg):
    with open(out_path, 'w') as fh:
        json.dump({'ok': False, 'error': msg}, fh)
    sys.exit(0)


try:
    import vlm_worker as W
    from PIL import Image
    with open(payload_path) as fh:
        cfg = json.load(fh)

    def log(m):
        print(m, file=sys.stderr, flush=True)

    processor, model = W._load_model(cfg['model_id'], cfg['device'],
                                     cfg['quantization'], 'auto', log_fn=log)
    placeholder = Image.new('RGB', (224, 224), (128, 128, 128))
    inputs, _rw, _rh = W._prepare_inputs(processor, [placeholder], cfg['prompt'],
                                         cfg['device'])
    text = W._generate(model, processor, inputs,
                       int(cfg.get('max_new_tokens', 1500)), 0.0)
    peak = 0.0
    try:
        import torch
        if cfg['device'] == 'cuda':
            peak = torch.cuda.max_memory_allocated() / (1024.0 ** 3)
    except Exception as _exc:
        log('peak VRAM query skipped: %s' % _exc)
    with open(out_path, 'w') as fh:
        json.dump({'ok': True, 'text': text, 'model': cfg['model_id'],
                   'device': cfg['device'], 'peak_vram_gb': round(peak, 2)}, fh)
except Exception as e:
    _err('%s: %s' % (type(e).__name__, e))
'''


def _fmt_metric_table(findings):
    rows = [
        '| finding | region | class | severity | status | source | key numbers vs threshold |',
        '|---|---|---|---|---|---|---|',
    ]
    for f in findings:
        nums = []
        for s in f['signals']:
            m = s.get('measured') or {}
            th = s.get('threshold') or {}
            if s['source'] == 'pixel' and isinstance(m, dict):
                if m.get('flow_mean') is not None:
                    nums.append(
                        f'flow {m["flow_mean"]} (min {th.get("min_flow")}), '
                        f'churn_p95 {m.get("churn_p95")} (max {th.get("max_churn_p95")})'
                    )
                elif m.get('ncc_min') is not None:
                    nums.append(f'prop NCC {m["ncc_min"]}-{m.get("ncc_max")} (min {th.get("ncc_min")})')
                elif m.get('detect_rate') is not None:
                    nums.append(f'hand detect rate {m["detect_rate"]}, issues {m.get("issue_counts")}')
                elif m.get('checks') is not None:
                    nums.append(f'{len(m["checks"])} ownership checks')
            else:
                nums.append(
                    f'{s["name"]}@{s.get("asked_on")}={s.get("answer")} (expected {s.get("expected")}, k={s.get("k")})'
                )
        rows.append(
            f'| {f["id"]} | {f["region"]} | {f["defect_class"]} | '
            f'{f["severity"]} | {f["status"].upper()} | {f["source"]} | '
            f'{"; ".join(nums)[:400]} |'
        )
    return '\n'.join(rows)


def _synthesis_prompt(clip, meta, preamble, findings, pixel, prior, targets, n_crops, dur, tier_note):
    beats = []
    for t in meta.get('draw_times') or []:
        beats.append(f'- t={t}s: the boy is scripted to write a line in the ledger')
    if meta.get('takeover_start') is not None:
        beats.append(f'- t={meta["takeover_start"]}s: scripted action takeover point')
    fails = [f for f in findings if f['status'] == 'fail']
    crit = [f for f in fails if f['severity'] == 'critical']
    unknown = [f for f in findings if f['status'] == 'unknown']
    headline = (
        f'{len(findings)} findings: {len(fails)} FAILING '
        f'({len(crit)} of them critical), {len(unknown)} undecidable, '
        f'{len(findings) - len(fails) - len(unknown)} passing.'
    )
    lines = []
    for f in findings:
        for s in f['signals']:
            # asked_on is NOT decorative: the same item is deliberately asked on
            # more than one crop (two_hands_each on the man crop AND the boy
            # crop), and two lines that both said "on frame" would look like the
            # judge contradicting itself rather than two different crops
            # answering two different questions about two different people.
            where = f['region']
            if s['source'] == 'vlm' and s.get('asked_on'):
                where = f'{f["region"]} (crop: {s["asked_on"]})'
            tag = f'[{s["source"]}] {s["name"]} on {where}: {s["status"].upper()}'
            if s['source'] == 'vlm' and s.get('skipped_reason'):
                # NEVER render an unasked question as if it had been answered.
                tag += (
                    f' — THIS QUESTION WAS NOT ASKED '
                    f'(reason: {s["skipped_reason"]}'
                    + (
                        '; identity checks need reference portraits, which were not supplied to this run'
                        if s['skipped_reason'] == 'no_items'
                        else ''
                    )
                    + '). Treat as NO COVERAGE, not as a pass.'
                )
            elif s['source'] == 'vlm':
                tag += (
                    f" (answered '{s.get('answer')}', a correct render answers "
                    f"'{s.get('expected')}', k={s.get('k')}, votes={s.get('votes')})"
                )
                if s.get('fail_times'):
                    tag += f' failing timestamps {s["fail_times"]}'
            else:
                tag += f' — {str(s.get("reason"))[:220]}'
            if s.get('reason') and s['source'] == 'vlm':
                tag += f' | judge\'s own words: "{str(s["reason"])[:200]}"'
            lines.append(tag)
        for c in f['caveats']:
            lines.append(f'[caveat] {f["id"]}: {c}')

    prior_txt = 'no prior runs recorded'
    if prior.get('trends'):
        prior_txt = '\n'.join(
            f'- gate {g["gate"]}: {g.get("passed")}/{g.get("n")} passed over the '
            f'window (recent half {g.get("recent_pass_rate")}, prior half '
            f'{g.get("prior_pass_rate")}), last seen {g.get("last_seen")}'
            + (
                f", TREND {g['shift'].upper()} (z={g.get('z')}) — this gate's pass "
                f'rate has MOVED, treat it as a regression signal'
                if g.get('shift')
                else ''
            )
            for g in prior['trends'][:18]
        )
    lessons_txt = 'none recorded for this scene'
    if prior.get('lessons'):
        lessons_txt = '\n'.join(
            f'- {l.get("ts")} run {l.get("run_id")}: {l.get("finding")} '
            f'({l.get("severity")}, witnesses {l.get("source")}) at t={l.get("times")}'
            for l in prior['lessons']
        )

    return f"""You are the QC analyst for a local AI video pipeline. The image attached to
this message is a blank grey placeholder with no information in it — IGNORE IT
COMPLETELY. Work only from the written evidence below.

Your job: write the operator-facing defect analysis for one finished render. The
operator has NOT seen the video. Nobody will interpret your output for them, so
it must stand alone.

=== THE RENDER ===
file: {os.path.basename(clip)}
duration: {dur:.2f}s
intended scene: {preamble}

Scripted beats from the shot metadata:
{chr(10).join(beats) or '- none recorded'}

=== HOW THE EVIDENCE WAS GATHERED ===
Two independent witnesses examined this clip.
1. A local vision-language judge answered fixed binary questions. It was shown
   {n_crops} REGION CROPS ({', '.join(sorted(targets))}), never bare frames,
   because the same judge is measurably blind to small defects at full-frame
   scale (5/5 correct on crops vs 0/2 on the full frame for the same defect).
   {tier_note}
2. Pixel metrics measured motion, structural churn, prop identity across the
   render's context-window seams, hand anatomy and grounded prop ownership. The
   judge is DOCUMENTED-BLIND to temporal defects (frozen limbs, seam morphing)
   and scored 0/7 on a confirmed ink defect, so those classes belong to the
   metrics alone. Every line below is tagged with which witness produced it.

=== EVIDENCE ===
{headline}

{chr(10).join(lines)}

=== MEASUREMENT TABLE (thresholds and pass/fail) ===
{_fmt_metric_table(findings)}

=== CROSS-RUN MEMORY (previous runs of this pipeline) ===
{prior_txt}

Previously recorded diagnoses for this scene:
{lessons_txt}

=== WHAT TO WRITE ===
Output GitHub-flavoured Markdown, no preamble, no restating of these
instructions, in exactly this structure:

## Verdict
ONE paragraph (4-7 sentences). State plainly whether this render is deliverable,
what the single most serious problem is, and how confident you are. Write it so
somebody who has never seen the video understands what the picture looks like.

## What is wrong
A bullet per real problem, worst first. Each bullet: what is wrong, WHERE
(region name and timestamps in seconds), how severe, and WHICH witness saw it
(judge / metrics / both). If only one witness saw it, say so and say what that
means for confidence.

## Suspected cause
For each problem, your best mechanical hypothesis about what in the pipeline
produced it — generation, post-processing, compositing, prompt, or the QC itself
being wrong. Reason from the pattern of the numbers. Say explicitly when a
measurement is consistent with a POST-PROCESSING step overwriting good generated
pixels rather than with a bad generation. Where two witnesses disagree, say which
one you believe and why.

## What I could not check
Anything the evidence cannot settle, including any check whose PASS is flagged
unreliable above. Do not pretend coverage you do not have.

## Next action
Two or three concrete, ordered steps for the operator.

Rules: never claim a defect the evidence does not support; never soften a
critical failure; quote the actual numbers; if everything passed, say so
plainly and do not invent problems."""


def _run_synthesis(prompt, tier, out_dir, log, log_fn, offload=True):
    """Boundary-tier synthesis behind comfy_offload.gpu_exclusive."""
    res = {
        'ok': False,
        'text': '',
        'error': None,
        'tier': tier,
        'model': None,
        'seconds': 0.0,
        'peak_vram_gb': None,
        'fell_back': None,
    }
    t0 = time.time()
    try:
        from zyg_workflows import vlm_inspector as VLM
    except Exception as e:
        res['error'] = f'vlm_inspector unavailable: {e}'
        return res
    if not VLM.available():
        res['error'] = f'judge venv/worker missing under {VLM.VLM_HOME}'
        return res

    runner = os.path.join(out_dir, '_synth_runner.py')
    payload_p = os.path.join(out_dir, '_synth_payload.json')
    outp = os.path.join(out_dir, '_synth_result.json')
    try:
        with open(runner, 'w', encoding='utf-8') as f:
            f.write(_SYNTH_RUNNER)
    except Exception as e:
        res['error'] = f'cannot write synthesis runner: {e}'
        return res

    def _attempt(t):
        cfg = VLM.TIERS[t]
        model_id = VLM.model_for(t)
        payload = {
            'model_id': model_id,
            'device': cfg['device'],
            'quantization': VLM._quant_for(t) if t != 'cpu' else 'none',
            'prompt': prompt,
            'max_new_tokens': SYNTH_TOKENS,
        }
        with open(payload_p, 'w', encoding='utf-8') as f:
            json.dump(payload, f)
        env = dict(os.environ)
        if cfg['device'] == 'cpu':
            env['CUDA_VISIBLE_DEVICES'] = ''
        log(f'synthesis: {model_id} tier={t} device={cfg["device"]} max_new_tokens={SYNTH_TOKENS}')
        r = subprocess.run(
            [VLM._VLM_PY, runner, VLM.VLM_HOME, payload_p, outp],
            capture_output=True,
            text=True,
            timeout=VLM.TIERS[t]['timeout_s'],
            env=env,
        )
        if r.returncode != 0:
            return {'ok': False, 'error': f'runner rc={r.returncode}: {(r.stderr or "")[-500:]}'}
        try:
            with open(outp, encoding='utf-8') as f:
                return json.load(f)
        except Exception as e:
            return {'ok': False, 'error': f'no runner output ({e}); stderr {(r.stderr or "")[-300:]}'}

    try:
        from zyg_workflows import comfy_offload as CO
    except Exception as e:
        log(f'comfy_offload unavailable ({e}) — refusing the GPU, using cpu tier')
        CO = None

    order = [tier] + [t for t in ('resident', 'cpu') if t != tier]
    got = None
    for t in order:
        needs_gpu = VLM.TIERS[t]['needs_gpu']
        if needs_gpu:
            if CO is None:
                continue
            try:
                if CO.comfy_is_sampling():
                    log('ComfyUI is SAMPLING — refusing GPU synthesis (a render is mid-sample)')
                    res['error'] = 'comfy_sampling'
                    return res
            except Exception as e:
                log(f'comfy_is_sampling failed ({e}) — assuming SAMPLING, refusing')
                res['error'] = 'comfy_sampling_unknown'
                return res
            need = VLM.TIERS[t]['min_free_gb']
            try:
                if offload:
                    # timeout_s is the polite-coordination knob: another agent's
                    # judge run holding ~12 GB is TRANSIENT, and waiting a few
                    # minutes for it to exit is strictly better than either
                    # killing it or silently downshifting the one step that most
                    # benefits from the 32B. gpu_exclusive yields the ACTUAL free
                    # GB whether or not the target was reached, so the check
                    # below is what decides.
                    with CO.gpu_exclusive(min_free_gb=need, timeout_s=SYNTH_WAIT_S, log_fn=log_fn) as free_gb:
                        log(f'gpu_exclusive: {float(free_gb or 0):.1f} GB free (tier {t} needs {need})')
                        if float(free_gb or 0) < need:
                            log(f'tier {t} does not fit — trying the next tier down')
                            continue
                        got = _attempt(t)
                else:
                    free_gb = CO.gpu_free_gb() or 0.0
                    if free_gb < need:
                        continue
                    got = _attempt(t)
            except Exception as e:
                log(f'gpu path failed for tier {t} ({e})')
                got = None
        else:
            got = _attempt(t)
        if got and got.get('ok') and (got.get('text') or '').strip():
            res.update(
                {
                    'ok': True,
                    'text': got['text'],
                    'tier': t,
                    'model': got.get('model'),
                    'peak_vram_gb': got.get('peak_vram_gb'),
                }
            )
            if t != tier:
                res['fell_back'] = f'{tier} -> {t}'
                log(f'SYNTHESIS FELL BACK {tier} -> {t}')
            break
        if got:
            log(f'tier {t} synthesis failed: {str(got.get("error"))[:400]}')
            res['error'] = str(got.get('error'))[:600]
    res['seconds'] = round(time.time() - t0, 1)
    return res

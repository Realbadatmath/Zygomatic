# ── the prompt itself is a lever, and a defect surface ───────────────────────
# Every tool below is ACTIVATED BY A PROMPT — a brief, a caption, a style tag, a question
# put to a judge, a line handed to a voice. The sheets above ask what the tool can do when
# it is asked well. These ask the operator's question instead: what does a badly written,
# over-long or ambiguous prompt cost us, and how much of the prompt does the tool actually
# read before it starts dropping terms?
#
# Two numbers matter and are almost never published. The HARD limit is where the prompt
# errors. The SOFT limit is where it silently stops reading — SDXL's CLIP encoder quietly
# truncates at 77 tokens, so a 90-word prompt renders a 60-word picture and nothing
# complains. A soft limit that nobody has measured is a prompt we are writing blind.
#
# Answers are numbers wherever a number exists (words, tokens, count) and a state
# otherwise. 'untested' is the honest default for nearly all of it.

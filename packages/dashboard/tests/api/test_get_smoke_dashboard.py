"""Read-only GET sweep of every dashboard route, as a permanent test.

WHAT THIS GUARDS
----------------
The dashboard exposes 264 GET-only rules. This module walks all of them with an
admin session through the in-process test client and asserts only that none of
them answers a server error. It is deliberately a *smoke* layer: it does not
know what any route should return, it knows that no route may crash.

WHY THE THREE CLASSES
---------------------
``apitests/routes.json`` (generated by the route-inventory task) classifies each
rule with two flags read off the handler:

* ``danger``   — the rule or endpoint name matches a verb that starts, deletes,
                 approves, restarts, installs, ... something. Calling it would
                 act on real production state under ``data/runtime``.
* ``external`` — the handler source calls out (requests, urlopen, subprocess,
                 ollama, anthropic, comfy, raw sockets). Calling it would hit a
                 third party or spawn a process.

Those are NEVER requested. They are emitted as explicit skips rather than
dropped, so the skip count is visible in ``-rs`` output and a route that silently
becomes dangerous (or stops being) shows up as a change in that count.

The rest split on whether the rule has path parameters. Parameterless rules are
fetched as-is; parameterised rules get a per-converter placeholder substituted,
which means the handler is asked about an object that does not exist — a 404 or a
400 is the expected answer there, and a 500 is the bug this catches.

503 is accepted throughout: several routes answer 503 as a legitimate
service-state reply (``/api/agents``, ``/api/gpu/schedule``) when the control
plane is not reachable from the test process.
"""

import re
import time

import pytest

pytestmark = pytest.mark.timeout(60)

# The slowest route measured on 2026-10-02 is /api/metrics/all at 13.1 s, so the
# 60 s per-test timeout above has ~4x headroom.
FAIL_STATUSES = (500, 502)

# Placeholder per Werkzeug converter. The point is to be syntactically valid for
# the converter while naming an object that cannot exist, so the handler takes
# its not-found branch instead of touching real data.
CONVERTER_VALUES = {
    'int': '1',
    'float': '1.0',
    'uuid': '00000000-0000-4000-8000-000000000000',
    'path': '__apitest__',
    'string': '__apitest__',
    'any': '__apitest__',
    'default': '__apitest__',
}

_PARAM_RE = re.compile(r'<([^>]+)>')

# Rows accumulated by every test in this module; written out once by the
# module-scoped fixture below, whose teardown runs after the last test.
_ROWS = []
_REPORT = []


def _fill(rule):
    """Substitute a placeholder for each ``<converter:name>`` in a Werkzeug rule."""

    def sub(match):
        inner = match.group(1)
        conv = inner.split(':', 1)[0] if ':' in inner else 'default'
        # 'any(a,b)' and 'string(minlength=2)' carry arguments; strip them.
        conv = conv.split('(', 1)[0]
        return CONVERTER_VALUES.get(conv, '__apitest__')

    return _PARAM_RE.sub(sub, rule)


def _get_rules(routes):
    return [r for r in routes['apps']['dashboard'] if r['methods'] == ['GET']]


def _ids(rules):
    return [r['rule'] for r in rules]


def _split(routes):
    """(safe, params, excluded) — the three classes described in the docstring."""
    rules = _get_rules(routes)
    safe, params, excluded = [], [], []
    for r in rules:
        if r['danger'] or r['external']:
            excluded.append(r)
        elif r['params']:
            params.append(r)
        else:
            safe.append(r)
    return safe, params, excluded


def _load_routes():
    """Read the inventory at collection time (fixtures are not available then).

    The ``routes`` fixture is still requested by every test so that a missing
    inventory produces its skip reason rather than a silent zero-test run.
    """
    import json
    from pathlib import Path

    crews_dir = Path(__file__).resolve().parents[2]
    return json.loads((crews_dir / 'apitests' / 'routes.json').read_text())


try:
    _ROUTES = _load_routes()
except Exception:  # inventory missing/unreadable: the `routes` fixture skips with a reason
    _ROUTES = {'apps': {'dashboard': []}}

_SAFE, _PARAMS, _EXCLUDED = _split(_ROUTES)


@pytest.fixture(autouse=True)
def _capture_report(report):
    """Hold on to the session's report writer so the module teardown can use it."""
    if not _REPORT:
        _REPORT.append(report)
    yield


@pytest.fixture(scope='module', autouse=True)
def _write_report():
    yield
    if not _REPORT or not _ROWS:
        return
    by_status = {}
    for row in _ROWS:
        by_status[str(row['status'])] = by_status.get(str(row['status']), 0) + 1
    slowest = sorted(_ROWS, key=lambda r: -r['ms'])[:10]
    _REPORT[0](
        'get_smoke_dashboard',
        {
            'summary': {
                'requested': len(_ROWS),
                'skipped_danger_or_external': len(_EXCLUDED),
                'safe_rules': len(_SAFE),
                'param_rules': len(_PARAMS),
                'counts_by_status': dict(sorted(by_status.items())),
                'slowest_10': slowest,
                'total_ms': round(sum(r['ms'] for r in _ROWS), 1),
            },
            'rows': sorted(_ROWS, key=lambda r: r['rule']),
        },
    )


def _sweep(client, route, url):
    started = time.perf_counter()
    resp = client.get(url)
    ms = round((time.perf_counter() - started) * 1000, 1)
    _ROWS.append(
        {
            'rule': route['rule'],
            'url': url,
            'endpoint': route['endpoint'],
            'status': resp.status_code,
            'ms': ms,
            'params': bool(route['params']),
        }
    )
    assert resp.status_code not in FAIL_STATUSES, (
        f'{route["rule"]} ({route["endpoint"]} at {route["func"]}) answered '
        f'{resp.status_code}; body starts: {resp.get_data(as_text=True)[:400]!r}'
    )


@pytest.mark.parametrize('route', _SAFE, ids=_ids(_SAFE))
def test_safe_get_does_not_crash(dash_admin, routes, route):
    """A parameterless, non-dangerous, non-external GET must not answer 5xx."""
    _sweep(dash_admin, route, route['rule'])


@pytest.mark.parametrize('route', _PARAMS, ids=_ids(_PARAMS))
def test_param_get_does_not_crash(dash_admin, routes, route):
    """Same, with a placeholder for each path parameter: 404/400 is fine, 500 is not."""
    _sweep(dash_admin, route, _fill(route['rule']))


@pytest.mark.parametrize('route', _EXCLUDED, ids=_ids(_EXCLUDED))
def test_excluded_get_is_not_called(routes, route):
    """Never requested — recorded as a skip so the excluded set stays visible."""
    reasons = []
    if route['danger']:
        reasons.append('danger (verb in rule/endpoint acts on real state)')
    if route['external']:
        reasons.append('external (handler calls out or spawns a process)')
    pytest.skip(f'{route["rule"]} not called: {" + ".join(reasons)} [{route["endpoint"]} at {route["func"]}]')

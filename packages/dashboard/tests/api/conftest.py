"""In-process API test harness for the Flask dashboard (crewai_web_gui).

WHY THE THREAD SUPPRESSION
--------------------------
Importing ``crewai_web_gui`` at module level starts ~19 background watcher
threads (market-scheduler, preempt-watcher, zero-approval-worker,
remix-watcher, storyteller-daily-watcher, sports-scheduler,
telemetry-sampler, ...). A pytest process runs on the same machine as the
LIVE GUI, so a second copy of those watchers would poll the same queues,
write the same runtime state files and race the production process. We
therefore neuter ``threading.Thread.start`` for the duration of the import
and restore it immediately afterwards, so the module's routes exist but none
of its workers ever run. The Otel exporter thread is the single exception:
its ``atexit`` handler joins it, and a thread that was never started raises
``RuntimeError: cannot join thread before it is started`` at interpreter
shutdown, so we let that one through.

WHY THE LIMITER IS OFF
----------------------
``g.limiter`` defaults to 200 requests/hour per remote address. A sweep over
the route inventory issues far more than that from one address, so every
request past the 200th would answer 429 and the tests would measure
Flask-Limiter instead of the API. ``limiter.enabled = False`` is set on the
imported module only — it never touches the live process.

WHY THE IMPORT MAY SKIP
-----------------------
``crewai_web_gui`` imports crewai (and, further down the module graph, mediapipe
and opencv) at module level. A checkout whose venv only carries the core set — a
CI runner, a reviewer's machine — cannot import it, and every test that wants a
route would then ERROR at setup with the same ModuleNotFoundError five hundred
times over. The fixture skips instead, naming the module that is missing. Run
``pip install -e ../zygomatic-workflows -e '.[gpu,audio,llm]'`` plus the hand-installed
packages listed in pyproject.toml to exercise the sweep for real.
"""

import json
import os
import socket
import threading
from pathlib import Path

import pytest

CREWS_DIR = Path(__file__).resolve().parents[2]
APITESTS_DIR = CREWS_DIR / 'apitests'
ROUTES_JSON = APITESTS_DIR / 'routes.json'
REPORTS_DIR = APITESTS_DIR / 'reports'

CSRF_TOKEN = 't' * 43


@pytest.fixture(scope='session')
def dash_app():
    """The imported crewai_web_gui module, with every watcher thread suppressed."""
    os.environ['CREWAI_PAGE_LOAD_DEBUG'] = '0'
    # The module itself imports fine without FLASK_SECRET_KEY — only serving refuses —
    # but routes that sign a session cookie need a key, so the harness supplies one.
    os.environ.setdefault('FLASK_SECRET_KEY', 'a' * 64)

    suppressed = []
    real_start = threading.Thread.start

    def _blocked_start(self):
        if self.name.startswith('Otel'):
            return real_start(self)
        suppressed.append(self.name)
        return None

    threading.Thread.start = _blocked_start
    try:
        from zyg_dashboard import crewai_web_gui as g
    except ModuleNotFoundError as exc:
        pytest.skip(f'crewai_web_gui needs a package this environment has not got: {exc}')
    finally:
        threading.Thread.start = real_start

    g.limiter.enabled = False
    socket.setdefaulttimeout(5)

    print(f'\n[api harness] suppressed {len(suppressed)} watcher threads: {", ".join(sorted(set(suppressed)))}')

    yield g

    alive = [t.name for t in threading.enumerate() if not t.name.startswith('Otel')]
    assert len(alive) == 1, f'background threads leaked into the test process: {alive}'


@pytest.fixture
def dash(dash_app):
    """Anonymous client. REMOTE_ADDR is test_client's default 127.0.0.1."""
    with dash_app.app.test_client() as c:
        yield c


@pytest.fixture
def dash_remote(dash_app):
    """Anonymous client from a non-localhost address (defeats the localhost bypass)."""
    with dash_app.app.test_client() as c:
        c.environ_base['REMOTE_ADDR'] = '10.0.0.9'
        yield c


@pytest.fixture
def dash_admin(dash_app):
    """Client carrying an admin session plus a ``csrf`` helper for body methods."""
    with dash_app.app.test_client() as c:
        with c.session_transaction() as s:
            s['user_role'] = 'admin'
            s['user_id'] = '__apitest__'
            s['user_name'] = 'apitest'
            s['_validity'] = dash_app.SESSION_VALIDITY_TOKEN
            s['_csrf_token'] = CSRF_TOKEN
        c.csrf = {'X-CSRF-Token': CSRF_TOKEN}
        yield c


@pytest.fixture(scope='session')
def routes():
    """The generated route inventory (apitests/routes.json)."""
    if not ROUTES_JSON.exists():
        pytest.skip(f'route inventory missing: {ROUTES_JSON} (generated by the route-inventory task of this tree)')
    return json.loads(ROUTES_JSON.read_text())


@pytest.fixture
def report():
    """``report(name, rows)`` writes rows as JSON to apitests/reports/<name>.json."""

    def _write(name, rows):
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        path = REPORTS_DIR / f'{name}.json'
        path.write_text(json.dumps(rows, indent=2, default=str))
        return path

    return _write
